#pragma once
#include <M5GFX.h>

// 1-bit pixel art, one char per pixel ('#' = on). Drawn scaled with no smoothing.
struct Bitmap {
  uint8_t w, h;
  const char* px;
};

inline void drawBitmap(lgfx::LGFX_Sprite& c, const Bitmap& b, int x, int y, int scale, uint16_t color) {
  for (int r = 0; r < b.h; r++)
    for (int col = 0; col < b.w; col++)
      if (b.px[r * b.w + col] == '#') c.fillRect(x + col * scale, y + r * scale, scale, scale, color);
}

